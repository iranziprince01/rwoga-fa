import { readdirSync, readFileSync, writeFileSync, statSync } from 'node:fs'
import { join, extname } from 'node:path'
import { config } from 'dotenv'
import { put } from '@vercel/blob'

config({ path: '.env.local' })
config({ path: '.env' })

const token = process.env.BLOB_READ_WRITE_TOKEN
if (!token) {
  console.error('Missing BLOB_READ_WRITE_TOKEN. Run: vercel env pull .env.local')
  process.exit(1)
}

const publicDir = join(process.cwd(), 'public')
const rasterExts = new Set(['.jpg', '.jpeg', '.png', '.webp', '.gif', '.avif'])

const files = readdirSync(publicDir)
  .filter((name) => {
    if (name.startsWith('.')) return false
    return rasterExts.has(extname(name).toLowerCase())
  })
  .sort((a, b) => a.localeCompare(b))

/** @type {Record<string, string>} */
const assets = {}

console.log(`Uploading ${files.length} photos to Vercel Blob…`)

for (const file of files) {
  const localPath = join(publicDir, file)
  const sizeMb = (statSync(localPath).size / (1024 * 1024)).toFixed(2)
  const pathname = `media/${file}`
  const body = readFileSync(localPath)

  process.stdout.write(`  ${file} (${sizeMb} MB)… `)

  const blob = await put(pathname, body, {
    access: 'public',
    token,
    addRandomSuffix: false,
    allowOverwrite: true,
    contentType: contentTypeFor(file),
  })

  assets[`/${file}`] = blob.url
  console.log('ok')
}

const sortedKeys = Object.keys(assets).sort((a, b) => a.localeCompare(b))
const lines = sortedKeys.map((key) => `  ${JSON.stringify(key)}: ${JSON.stringify(assets[key])},`)

const output = `/* Auto-generated by scripts/upload-blob-assets.mjs — do not edit by hand */
export const blobAssets = {
${lines.join('\n')}
} as const

export type BlobAssetPath = keyof typeof blobAssets
`

const outPath = join(process.cwd(), 'src/data/blobAssets.ts')
writeFileSync(outPath, output)
console.log(`\nWrote ${sortedKeys.length} CDN URLs → ${outPath}`)

/**
 * @param {string} file
 */
function contentTypeFor(file) {
  switch (extname(file).toLowerCase()) {
    case '.jpg':
    case '.jpeg':
      return 'image/jpeg'
    case '.png':
      return 'image/png'
    case '.webp':
      return 'image/webp'
    case '.gif':
      return 'image/gif'
    case '.avif':
      return 'image/avif'
    default:
      return undefined
  }
}
